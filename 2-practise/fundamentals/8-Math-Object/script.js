// Math Object

// Math.round()
console.log(Math.round(4.6));  // 5
console.log(Math.round(4.4)); // 4

// Math.floor()
console.log(Math.floor(4.8)); // 4
console.log(Math.floor(4.3)); // 4

// Math.ceil()
console.log(Math.ceil(4.8)); // 5
console.log(Math.ceil(4.3)); // 5

// Math.trunc()
console.log(Math.trunc(4.6));  // 4
console.log(Math.trunc(-4.2));  // -4

// Math.random()
console.log(Math.random()); // 0.9702........
console.log(Math.round(Math.random()));


// Math.max()
console.log(Math.max(3,4,5,6,33,45,32,32,12,34));

// Math.min()
console.log(Math.min(3,4,5,6,33,45,32,32,12,34));


// Math.abs()
console.log(Math.abs(-30));  // 30
console.log(Math.abs(34));   // 34

// Math.pow()
console.log(Math.pow(2, 3)); // 8

// Math.sqrt()
console.log(Math.sqrt(25)); // 5