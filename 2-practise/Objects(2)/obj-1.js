// Object basics ----

// an object declaration -- literal
const user = {
    name: "reze",
    age: 24,
    gender: "male",
    status: "student",
    isLoyal: false
}

console.log(user.name);  // reze
console.log(user.isLoyal); // false

// constructor --
const person = new Object();
person.name = "John";
person.age = 32;

console.log(person);

