// ternary 

// 01 - even odd check

function checkEvenOdd(a) {
    return a%2 === 0 ? "even" : "odd";

}

let checkresult = checkEvenOdd(3);
console.log(checkresult);


// 02 - pass or fail

function checkResult(marks) {
    return marks >= 33 ? "pass" : "fail";

}

let checkoutput = checkResult(33);
console.log(checkoutput);